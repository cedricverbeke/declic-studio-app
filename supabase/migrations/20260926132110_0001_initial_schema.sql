/*
# Déclic Studio — Initial schema

1. New Tables
- `pricing_tiers`: named price grids (e.g. "Tarif Studio"). `rates` JSON stores
  degressive tiered pricing as { tiers: [{ qty, price }], extra_per_photo }.
  `is_default` marks the default grid.
- `sessions`: a photo session identified by a unique human-readable code
  (e.g. DS-8493), linked to a pricing tier, with a status of
  'pending' | 'active' | 'completed'. Only one session can be 'active' at a time
  (enforced by a partial unique index).
- `photos`: photos belonging to a session, with a filename and a vignette URL.
  `hd_ready` tracks whether the HD file has been uploaded to private storage.
- `orders`: a client order on a session: selected photos (array of photo ids),
  customer email, amount, payment status, delivery status, timestamps.

2. Security
- This is a no-auth app (no sign-in screen). The photographer back-office and
  the public client gallery both use the anon key, so all policies are scoped
  to `TO anon, authenticated` with `USING (true)` because the data is
  intentionally public/shared.
- RLS is enabled on every table.

3. Storage
- `vignettes` public bucket (public read).
- `hd-photos` private bucket (read via signed URLs through the back-office /
  edge function only).

4. Important notes
- `sessions.code` is unique and generated by the app (DS-XXXX format).
- A partial unique index ensures at most one 'active' session.
- `pricing_tiers.is_default` defaults to false; the app enforces a single
  default by clearing other rows before setting one (done client-side).
*/

-- ===== pricing_tiers =====
CREATE TABLE IF NOT EXISTS pricing_tiers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  rates jsonb NOT NULL DEFAULT '{}'::jsonb,
  is_default boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE pricing_tiers ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "anon_select_pricing_tiers" ON pricing_tiers;
CREATE POLICY "anon_select_pricing_tiers" ON pricing_tiers FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_pricing_tiers" ON pricing_tiers;
CREATE POLICY "anon_insert_pricing_tiers" ON pricing_tiers FOR INSERT
  TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_pricing_tiers" ON pricing_tiers;
CREATE POLICY "anon_update_pricing_tiers" ON pricing_tiers FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_delete_pricing_tiers" ON pricing_tiers;
CREATE POLICY "anon_delete_pricing_tiers" ON pricing_tiers FOR DELETE
  TO anon, authenticated USING (true);

-- ===== sessions =====
CREATE TABLE IF NOT EXISTS sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code text NOT NULL UNIQUE,
  pricing_tier_id uuid REFERENCES pricing_tiers(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'active'
    CHECK (status IN ('pending','active','completed')),
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;

CREATE UNIQUE INDEX IF NOT EXISTS sessions_one_active
  ON sessions (id) WHERE status = 'active';

DROP POLICY IF EXISTS "anon_select_sessions" ON sessions;
CREATE POLICY "anon_select_sessions" ON sessions FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_sessions" ON sessions;
