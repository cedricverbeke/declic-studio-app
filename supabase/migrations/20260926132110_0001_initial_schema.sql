-- ===== orders =====
CREATE TABLE IF NOT EXISTS orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id uuid NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
  customer_email text NOT NULL,
  selected_photos uuid[] NOT NULL DEFAULT '{}'::uuid[],
  amount numeric(10,2) NOT NULL DEFAULT 0,
  payment_status text NOT NULL DEFAULT 'pending'
    CHECK (payment_status IN ('pending','paid')),
  delivery_status text NOT NULL DEFAULT 'awaiting_hd'
    CHECK (delivery_status IN ('awaiting_hd','ready','delivered')),
  created_at timestamptz NOT NULL DEFAULT now(),
  paid_at timestamptz,
  delivered_at timestamptz
);
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS orders_session_id_idx ON orders (session_id);
CREATE INDEX IF NOT EXISTS orders_status_idx ON orders (delivery_status);

