-- ===== Storage buckets =====
INSERT INTO storage.buckets (id, name, public)
VALUES ('vignettes', 'vignettes', true)
ON CONFLICT (id) DO NOTHING;

INSERT INTO storage.buckets (id, name, public)
VALUES ('hd-photos', 'hd-photos', false)
ON CONFLICT (id) DO NOTHING;

-- Vignettes: public read, anyone upload/update/delete (anon-key app)
DROP POLICY IF EXISTS "anon_read_vignettes" ON storage.objects;
CREATE POLICY "anon_read_vignettes" ON storage.objects
  FOR SELECT TO anon, authenticated
  USING (bucket_id = 'vignettes');

DROP POLICY IF EXISTS "anon_insert_vignettes" ON storage.objects;
CREATE POLICY "anon_insert_vignettes" ON storage.objects
  FOR INSERT TO anon, authenticated
  WITH CHECK (bucket_id = 'vignettes');

DROP POLICY IF EXISTS "anon_update_vignettes" ON storage.objects;
CREATE POLICY "anon_update_vignettes" ON storage.objects
  FOR UPDATE TO anon, authenticated
  USING (bucket_id = 'vignettes') WITH CHECK (bucket_id = 'vignettes');

DROP POLICY IF EXISTS "anon_delete_vignettes" ON storage.objects;
CREATE POLICY "anon_delete_vignettes" ON storage.objects
  FOR DELETE TO anon, authenticated
  USING (bucket_id = 'vignettes');

